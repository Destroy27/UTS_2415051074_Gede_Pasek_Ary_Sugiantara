CREATE TABLE IF NOT EXISTS public.merchant_inventory (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id text NOT NULL DEFAULT '2415051074',
  product_id integer NOT NULL DEFAULT 0,
  product_title text NOT NULL,
  category text NOT NULL DEFAULT 'Sembako & Harian',
  buy_price integer NOT NULL DEFAULT 0,
  sell_price integer NOT NULL DEFAULT 0,
  stock_qty integer NOT NULL DEFAULT 0,
  restock_status text NOT NULL DEFAULT 'Stok Aman',
  merchant_note text NOT NULL DEFAULT '',
  rating integer NOT NULL DEFAULT 5 CHECK (rating >= 1 AND rating <= 5),
  thumbnail_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Aktifkan Row Level Security (RLS) sesuai praktik keamanan Supabase
ALTER TABLE public.merchant_inventory ENABLE ROW LEVEL SECURITY;

-- Kebijakan (Policies) untuk mengizinkan operasi CRUD menggunakan Anon/Publishable Key pada demo UTS
DROP POLICY IF EXISTS "Allow public select merchant_inventory" ON public.merchant_inventory;
CREATE POLICY "Allow public select merchant_inventory"
  ON public.merchant_inventory
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert merchant_inventory" ON public.merchant_inventory;
CREATE POLICY "Allow public insert merchant_inventory"
  ON public.merchant_inventory
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update merchant_inventory" ON public.merchant_inventory;
CREATE POLICY "Allow public update merchant_inventory"
  ON public.merchant_inventory
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete merchant_inventory" ON public.merchant_inventory;
CREATE POLICY "Allow public delete merchant_inventory"
  ON public.merchant_inventory
  FOR DELETE
  TO anon, authenticated
  USING (true);

